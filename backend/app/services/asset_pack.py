def slug(text: str, fallback: str = "x", limit: int = 24) -> str:
    """Lowercase ASCII words joined by hyphens, cut to `limit` characters at a word boundary."""
    full = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    if len(full) <= limit:
        return full or fallback
    cut = full[:limit]
    return (cut.rsplit("-", 1)[0] if full[limit] != "-" and "-" in cut else cut).strip("-") or fallback


def stem(campaign_slug: str, version_slug: str, region_code: str, channel: str) -> str:
    return f"omc_{campaign_slug}_{version_slug}_{region_code}_{channel}"


def _ext(content_type: str, filename: str) -> str:
    return EXTENSIONS.get(content_type) or (filename.rsplit(".", 1)[-1].lower() if "." in filename else "bin")[:8]


def srt_time(ms: int) -> str:
    h, rest = divmod(max(ms, 0), 3_600_000)
    mnt, rest = divmod(rest, 60_000)
    sec, milli = divmod(rest, 1000)
    return f"{h:02}:{mnt:02}:{sec:02},{milli:03}"


def build_srt(elements: list[dict[str, Any]], scenes: dict[str, tuple[int, int | None]]) -> str | None:
    """An SRT from the caption elements that sit in a timed scene; captions that share a scene split it evenly. None when no
    caption can be timed."""
    by_scene: dict[str, list[str]] = {}
    for e in elements:
        scene = e.get("scene_id")
        if e.get("kind") == "caption" and isinstance(e.get("value"), str) and e["value"].strip() and scene in scenes:
            by_scene.setdefault(scene, []).append(e["value"].strip())
    cues: list[tuple[int, int, str]] = []
    for scene, texts in by_scene.items():
        start, end = scenes[scene]
        if end is None or end <= start:
            continue
        step = (end - start) // len(texts)
        cues += [(start + i * step, end if i == len(texts) - 1 else start + (i + 1) * step, text) for i, text in enumerate(texts)]
    if not cues:
        return None
    cues.sort()
    return "\n".join(f"{n}\n{srt_time(a)} --> {srt_time(b)}\n{text}\n" for n, (a, b, text) in enumerate(cues, 1))


def copy_text(manifest_head: dict[str, Any], elements: list[dict[str, Any]]) -> str:
    lines = [f"{k}: {v}" for k, v in manifest_head.items() if v] + [""]
    for e in elements:
        if e.get("kind") in TEXT_KINDS and isinstance(e.get("value"), str):
            lines.append(f"[{e['kind']}] {e['id']}" + (f" ({e['language']})" if e.get("language") else "") + f": {e['value']}")
    return "\n".join(lines) + "\n"


def channel_for(kind: str, ids: set[str], channels: list[dict[str, Any]]) -> tuple[str, list[str], d.ChannelMatch]:
    """(channel for the file name, the other channels it serves, how it matched)."""
    explicit = [c["id"] for c in channels if c.get("creative_ref") in ids]
    if explicit:
        return explicit[0], explicit[1:], "creative_ref"
    by_format = [c["id"] for c in channels if kind in (c.get("format") or "").lower()]
    if by_format:
        return by_format[0], by_format[1:], "format"
    return "all", [], "none"



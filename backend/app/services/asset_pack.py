def _summary(row: m.AssetPack, region_name: str, version_label: str, by_name: str | None, now: datetime) -> d.AssetPackSummary:
    return d.AssetPackSummary(
        id=row.id, campaign_id=row.campaign_id, region_code=row.region_code, region_name=region_name, version_id=row.version_id,
        version_label=version_label, filename=row.filename, byte_size=row.byte_size, sha256=row.sha256, file_count=row.file_count,
        status="active" if row.expires_at > now else "expired", expires_at=row.expires_at, created_at=row.created_at,
        created_by_name=by_name, mode=row.mode,  # type: ignore[arg-type]
    )


async def preview(user_id: UUID, campaign_id: UUID, region_code: str) -> d.AssetPackPreview:
    """What a pack for the region would hold, read without building it. Any workspace member may look."""
    loaded = await _load(user_id, campaign_id, region_code, None, writable=False)
    ttl = get_settings().asset_pack_url_ttl_seconds
    if isinstance(loaded, _Blocked):
        return d.AssetPackPreview(
            region_code=loaded.region.code, region_name=loaded.region.name, can_build=False, approved_versions=loaded.approved, manifest=None,
            url_ttl_seconds=ttl,
            blocked_reason="No version has a standing approval for this region. Record an approval in the Readiness Board first.")
    built = await _assemble(loaded, read_bytes=False)
    return d.AssetPackPreview(
        region_code=loaded.region.code, region_name=loaded.region.name, can_build=True, blocked_reason=None, approved_versions=loaded.approved,
        manifest=built.manifest, url_ttl_seconds=ttl)


async def create_pack(user_id: UUID, campaign_id: UUID, body: d.AssetPackCreate) -> d.AssetPackCreated:
    loaded = await _load(user_id, campaign_id, body.region_code, body.version_id, writable=True)
    if isinstance(loaded, _Blocked):
        raise Conflict("No version has a standing approval for this region, so there is nothing to pack. Record an approval first.")
    src = loaded
    built = await _assemble(src, read_bytes=True)
    settings = get_settings()
    if sum(len(b) for b in built.payloads.values()) > settings.asset_pack_max_bytes:
        raise Conflict(f"The files are larger than the {settings.asset_pack_max_bytes // (1024 * 1024)} MB limit for one pack.")
    now = utcnow()
    manifest = built.manifest.model_copy(update={"generated_at": now})
    data = await asyncio.to_thread(build_zip, manifest, built.payloads, now)
    pack_id = uuid4()
    filename = f"omc_{manifest.campaign_slug}_{slug(src.node.label, 'version')}_{src.region.code}.zip"
    key = f"delivery/{src.project.id}/{pack_id}.zip"
    in_database = settings.asset_storage_backend == "database"
    token = secrets.token_urlsafe(32)
    expires = now + timedelta(seconds=settings.asset_pack_url_ttl_seconds)
    if not in_database:
        await blobs.store(key, data, "application/zip")
    try:
        async with session() as s, s.begin():
            by_name = await s.scalar(select(m.User.display_name).where(m.User.id == user_id))
            row = m.AssetPack(
                id=pack_id, project_id=src.project.id, campaign_id=src.campaign.id, region_code=src.region.code, version_id=src.node.id,
                approval_id=src.approval_id, filename=filename, byte_size=len(data), sha256=hashlib.sha256(data).hexdigest(),
                file_count=len(manifest.files) + 2, storage_key=key, data=data if in_database else None,
                manifest=manifest.model_dump(mode="json"), token_hash=hashlib.sha256(token.encode()).hexdigest(), expires_at=expires,
                mode=src.project.mode, created_by=user_id, created_at=now,
            )
            s.add(row)
            project = await s.get(m.Project, src.project.id)
            if project is not None:
                touch(project)
            await record_audit(
                s, action="asset_pack.build", target_type="asset_pack", target_id=str(pack_id), workspace_id=src.project.workspace_id,
                actor_user_id=user_id, detail={"region": src.region.code, "version_id": str(src.node.id), "approval_id": str(src.approval_id),
                                               "files": len(manifest.files), "excluded": len(manifest.excluded), "bytes": len(data)},
            )
    except Exception:
        if not in_database:
            await blobs.discard([key])
        raise
    summary = _summary(row, src.region.name, src.node.label, by_name, now)
    return d.AssetPackCreated(**summary.model_dump(), download_url=f"{API}/asset-packs/{pack_id}/download?token={token}", manifest=manifest)


async def list_packs(user_id: UUID, campaign_id: UUID, limit: int, offset: int) -> d.AssetPackPage:
    async with read_session() as s:
        campaign, _ = await get_owned(s, m.Campaign, campaign_id, user_id, "Campaign")
        stmt = (
            select(m.AssetPack, m.Region.name, m.VersionNode.label, m.User.display_name)
            .join(m.Region, m.Region.code == m.AssetPack.region_code)
            .join(m.VersionNode, m.VersionNode.id == m.AssetPack.version_id)
            .join(m.User, m.User.id == m.AssetPack.created_by)
            .where(m.AssetPack.campaign_id == campaign.id)
            .order_by(m.AssetPack.created_at.desc(), m.AssetPack.id.desc())
        )
        rows, total = await paginate(s, stmt, limit, offset)
    now = utcnow()
    return d.AssetPackPage(items=[_summary(r, region, label, by, now) for r, region, label, by in rows], limit=limit, offset=offset, total=total)


async def get_pack(user_id: UUID, pack_id: UUID) -> d.AssetPackDetail:
    async with read_session() as s:
        row, _ = await get_owned(s, m.AssetPack, pack_id, user_id, "Asset pack")
        region = await s.scalar(select(m.Region.name).where(m.Region.code == row.region_code))
        label = await s.scalar(select(m.VersionNode.label).where(m.VersionNode.id == row.version_id))
        by = await s.scalar(select(m.User.display_name).where(m.User.id == row.created_by))
    return d.AssetPackDetail(**_summary(row, region or row.region_code, label or "", by, utcnow()).model_dump(),
                             manifest=d.AssetPackManifest.model_validate(row.manifest))


async def download(pack_id: UUID, token: str) -> Response:
    """The stored ZIP for a valid, unexpired link. Every failure is the same 404, so a link reveals nothing."""
    async with read_session() as s:
        row = await s.get(m.AssetPack, pack_id)
    expected = row.token_hash if row is not None else hashlib.sha256(b"").hexdigest()
    valid = hmac.compare_digest(expected, hashlib.sha256(token.encode()).hexdigest())
    if row is None or not valid or row.expires_at <= utcnow():
        raise NotFound("The asset pack was not found, or its link has expired.")
    data = row.data
    if data is None:
        data = await blobs.read(cast(Any, SimpleNamespace(id=row.id, project_id=row.project_id, storage_name=row.storage_key)))
    return Response(
        data, media_type="application/zip",
        headers=blobs.CONTENT_HEADERS | {"Content-Disposition": f'attachment; filename="{row.filename}"'},
    )

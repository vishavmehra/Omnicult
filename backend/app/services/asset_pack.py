async def region_creatives(
    s: AsyncSession, campaign_id: UUID, region_code: str
) -> tuple[list[tuple[m.CreativeAsset, m.Asset]], list[tuple[m.CreativeAsset, str]]]:
    """This campaign's creatives made for the region with stored files and confirmed rights, and the others with the reason.
    Shared by the Asset Pack, the review page and the Region Plan, so the three agree on what a region's creative files are."""
    rows = (await s.execute(
        select(m.CreativeAsset, m.Asset).join(m.Asset, (m.Asset.id == m.CreativeAsset.asset_id) & (m.Asset.project_id == m.CreativeAsset.project_id))
        .where(m.CreativeAsset.campaign_id == campaign_id).order_by(m.CreativeAsset.created_at, m.CreativeAsset.id)
    )).all()
    ok: list[tuple[m.CreativeAsset, m.Asset]] = []
    left: list[tuple[m.CreativeAsset, str]] = []
    for creative, asset in rows:
        if creative.region_code is None:
            left.append((creative, "No region is set on this creative, so it is not assigned to a region's pack."))
        elif creative.region_code != region_code:
            left.append((creative, f"Made for {creative.region_code}, not {region_code}."))
        elif asset.upload_status != "stored":
            left.append((creative, "The upload did not complete."))
        elif not asset.rights_confirmed:
            left.append((creative, "Rights were not confirmed when the file was uploaded."))
        else:
            ok.append((creative, asset))
    return ok, left


async def approved_for(s: AsyncSession, campaign_id: UUID, region_id: UUID) -> list[Any]:
    """Standing approvals for a region: the newest decision of each version is an approve. Newest decision first."""
    latest = await launch._latest_approvals(s, campaign_id)  # noqa: SLF001  (the one reader of "latest decision per version")
    rows = [a for (rid, _), a in latest.items() if rid == region_id and a.decision == "approve"]
    return sorted(rows, key=lambda a: (a.decided_at, str(a.id)), reverse=True)


@dataclass
class _Blocked:
    region: m.Region
    approved: list[d.PackVersion]


async def _load(user_id: UUID, campaign_id: UUID, region_code: str, version_id: UUID | None, *, writable: bool) -> _Source | _Blocked:
    """The pack's sources, or `_Blocked` when the region has no standing approval."""
    async with read_session() as s:
        campaign, project = await get_owned(s, m.Campaign, campaign_id, user_id, "Campaign")
        if writable:
            require_writable(project)
        region = await s.scalar(select(m.Region).where(m.Region.code == region_code))
        if region is None:
            raise not_found("Region", "region_code")
        approvals = await approved_for(s, campaign.id, region.id)
        nodes = {n.id: n for n in (await s.execute(select(m.VersionNode).where(m.VersionNode.id.in_([a.version_id for a in approvals])))).scalars()} if approvals else {}
        approved = [_version_view(nodes[a.version_id]) for a in approvals if a.version_id in nodes]
        if version_id is not None and version_id not in {a.version_id for a in approvals}:
            raise Conflict("That version has no standing approval for this region, so it cannot be packed.")
        chosen = next((a for a in approvals if version_id in (None, a.version_id)), None)
        if chosen is None:
            return _Blocked(region, approved)
        node = nodes[chosen.version_id]
        brief = await s.scalar(select(m.CampaignBriefRow).where(m.CampaignBriefRow.campaign_id == campaign.id).order_by(m.CampaignBriefRow.version_number.desc()).limit(1))
        content = desk_schema.BriefContent.model_validate(brief.content) if brief else None
        ok, left = await region_creatives(s, campaign.id, region_code)
        creatives = [_Creative(c.label, c.kind, {str(c.id), str(c.asset_id), c.label}, a, f"Creative {c.id}: uploaded file {a.filename} (asset {a.id}).") for c, a in ok]
        excluded = [d.PackExcluded(kind="creative", label=c.label, reason=why) for c, why in left]
        seen = {c.asset.id for c in creatives} | {c.asset_id for c, _ in left}
        refs = [r for r in _asset_refs(node.elements) if r not in seen]  # files that other tools put straight into the version
        if refs:
            for a in (await s.execute(select(m.Asset).where(m.Asset.project_id == project.id, m.Asset.id.in_(refs), m.Asset.parent_asset_id.is_(None)))).scalars():
                if a.upload_status == "stored" and a.rights_confirmed:
                    creatives.append(_Creative(a.filename, a.kind, {str(a.id)}, a, f"Asset {a.id}, named by an element of version {node.id}."))
                else:
                    excluded.append(d.PackExcluded(kind="creative", label=a.filename, reason="The upload did not complete." if a.upload_status != "stored" else "Rights were not confirmed when the file was uploaded."))
        scene_ids = [UUID(str(e["scene_id"])) for e in node.elements if e.get("scene_id") and _is_uuid(e["scene_id"])]
        scene_rows = (await s.execute(select(m.CreativeScene).where(m.CreativeScene.campaign_id == campaign.id, m.CreativeScene.id.in_(scene_ids)))).scalars() if scene_ids else []
        design_row = await s.scalar(select(m.BrandKitDesignRow).where(m.BrandKitDesignRow.project_id == project.id))
        design = desk_schema.KitDesign.model_validate(design_row.design) if design_row else None
        kit_items: list[tuple[str, str, m.Asset]] = []
        kit_missing: list[tuple[str, str, str]] = []
        if design:
            wanted = [("logo", x.id, x.asset_id) for x in design.logo.lockups] + [("product", x.id, x.asset_id) for x in design.product_images]
            assets = {a.id: a for a in (await s.execute(select(m.Asset).where(m.Asset.project_id == project.id, m.Asset.id.in_([w[2] for w in wanted if w[2]])))).scalars()} if wanted else {}
            for role, item_id, asset_id in wanted:
                asset = assets.get(asset_id) if asset_id else None
                if asset is None:
                    kit_missing.append((role, item_id, "No uploaded file is linked to this Brand Kit item."))
                elif asset.upload_status != "stored" or not asset.rights_confirmed:
                    kit_missing.append((role, item_id, "Rights were not confirmed when the file was uploaded." if asset.upload_status == "stored" else "The upload did not complete."))
                else:
                    kit_items.append((role, item_id, asset))
        approval = _approval_view(chosen)
        return _Source(
            campaign=campaign, project=project, region=region, node=node, approval=approval, approval_id=chosen.id, approved=approved,
            brief_channels=[c.model_dump(mode="json") for c in content.channels] if content else [],
            primary_message=content.primary_message if content else None,
            scenes={str(r.id): (r.start_ms, r.end_ms) for r in scene_rows}, creatives=creatives, excluded=excluded,
            kit_items=kit_items, kit_missing=kit_missing,
            kit_data=design.model_dump(mode="json") if design else None,
        )


def _asset_refs(elements: list[dict[str, Any]]) -> list[UUID]:
    """Asset ids that elements name: a bare id string, or {"asset_id": id} (the shape the image tools use)."""
    found: dict[UUID, None] = {}
    for e in elements:
        value = e.get("value")
        raw = value.get("asset_id") if isinstance(value, dict) else value
        if isinstance(raw, str) and _is_uuid(raw):
            found[UUID(raw)] = None
    return list(found)


def _is_uuid(value: Any) -> bool:
    try:
        UUID(str(value))
    except ValueError:
        return False
    return True


def _approval_view(approval: Any) -> d.PackApproval:
    return d.PackApproval(
        id=approval.id, decision="approve", decided_by_name=approval.decided_by_name, decided_at=approval.decided_at, reason=approval.reason,
        verdict_at_decision=approval.verdict_at_decision, overrides_recommendation=approval.overrides_recommendation,
    )


# --- assembling the manifest and the files ----------------------------------------------------------------------------------


@dataclass
class _Built:
    manifest: d.AssetPackManifest
    payloads: dict[str, bytes]


def _file(path: str, role: str, data: bytes, source: str, *, asset: m.Asset | None = None, channel: str = "all",
          match: str = "none", also: list[str] | None = None) -> d.PackFile:
    return d.PackFile(
        path=path, role=role, size=len(data), sha256=hashlib.sha256(data).hexdigest(), source=source,  # type: ignore[arg-type]
        asset_id=asset.id if asset else None, rights_confirmed_at=asset.rights_confirmed_at if asset else None, channel=channel,
        also_channels=also or [], channel_match=match, width=asset.width if asset else None, height=asset.height if asset else None,  # type: ignore[arg-type]
    )


async def _assemble(src: _Source, *, read_bytes: bool) -> _Built:
    """The manifest and, when `read_bytes`, the file contents. A preview reads no bytes: it trusts the recorded SHA-256 and size."""
    c_slug, v_slug = slug(src.campaign.name, "campaign"), slug(src.node.label, "version")
    region_code = src.region.code
    base = lambda channel: stem(c_slug, v_slug, region_code, channel)  # noqa: E731
    files: list[d.PackFile] = []
    payloads: dict[str, bytes] = {}
    excluded = list(src.excluded)
    excluded += [d.PackExcluded(kind=f"brand_kit_{role}", label=item_id, reason=why) for role, item_id, why in src.kit_missing]
    elements = [dict(e) for e in src.node.elements]

    async def add_asset(path: str, role: str, asset: m.Asset, label: str, source: str, **channel: Any) -> bool:
        if read_bytes:
            try:
                data = await blobs.read(asset)
            except NotFound:
                excluded.append(d.PackExcluded(kind=role, label=label, reason="The stored file could not be found."))
                return False
            if hashlib.sha256(data).hexdigest() != asset.sha256:
                excluded.append(d.PackExcluded(kind=role, label=label, reason="The stored bytes do not match the SHA-256 recorded at upload, so the file was left out."))
                return False
            payloads[path] = data
            files.append(_file(path, role, data, source, asset=asset, **channel))
        else:
            files.append(d.PackFile(
                path=path, role=role, size=asset.size_bytes, sha256=asset.sha256, source=source, asset_id=asset.id,  # type: ignore[arg-type]
                rights_confirmed_at=asset.rights_confirmed_at, channel=channel.get("channel", "all"), also_channels=channel.get("also") or [],
                channel_match=channel.get("match", "none"), width=asset.width, height=asset.height))
        return True

    def add_bytes(path: str, role: str, data: bytes, source: str, **channel: Any) -> None:
        payloads[path] = data
        files.append(_file(path, role, data, source, **channel))

    head = {
        "Campaign": src.campaign.name, "Region": f"{src.region.name} ({region_code})", "Version": src.node.label,
        "Language": src.node.language, "Primary message": src.primary_message,
    }
    copy = {
        "schema": "omnicult-copy-1", "campaign": {"id": str(src.campaign.id), "name": src.campaign.name},
        "region": {"code": region_code, "name": src.region.name},
        "version": {"id": str(src.node.id), "label": src.node.label, "language": src.node.language, "actor": src.node.actor,
                    "created_at": src.node.created_at.isoformat(), "operation_id": str(src.node.operation_id) if src.node.operation_id else None},
        "primary_message": src.primary_message, "elements": elements,
    }
    add_bytes(f"copy/{base('all')}.json", "copy_json", (json.dumps(copy, ensure_ascii=False, indent=2) + "\n").encode(),
              f"Version {src.node.id}: every element of the approved version.")
    add_bytes(f"copy/{base('all')}.txt", "copy_text", copy_text(head, elements).encode(),
              f"Version {src.node.id}: the text elements of the approved version.")

    videos: list[tuple[str, str]] = []  # (file stem, channel) of each included video, so its captions sit beside it
    for creative in src.creatives:
        asset = creative.asset
        channel, also, match = channel_for(creative.kind, creative.ids, src.brief_channels)
        ext = _ext(asset.content_type, asset.filename)
        path = f"creatives/{base(channel)}.{ext}"
        if any(f.path == path for f in files):  # two creatives of one kind for one channel: keep both, numbered
            path = f"creatives/{base(channel)}-{sum(f.role == 'creative' for f in files) + 1}.{ext}"
        if await add_asset(path, "creative", asset, creative.label, creative.source, channel=channel, also=also, match=match) and creative.kind == "video":
            videos.append((path.removeprefix("creatives/").rsplit(".", 1)[0], channel))
    srt = build_srt(elements, src.scenes)
    if srt:
        for name, channel in videos or [(base("all"), "all")]:
            add_bytes(f"captions/{name}.srt", "captions", srt.encode(), f"Caption elements of version {src.node.id}, timed by their scenes' bounds.",
                      channel=channel)
    for role, item_id, asset in src.kit_items:
        await add_asset(f"brand-kit/{role}-{slug(item_id)}.{_ext(asset.content_type, asset.filename)}", "brand_kit_file", asset, item_id,
                        f"Brand Kit {role} {item_id}: uploaded file {asset.filename} (asset {asset.id}).")
    if src.kit_data is not None:
        add_bytes("brand-kit/brand-kit.json", "brand_kit_data", (json.dumps(src.kit_data, ensure_ascii=False, indent=2) + "\n").encode(),
                  f"Brand Kit design of project {src.project.id}.")
    files.sort(key=lambda f: f.path)
    counts: dict[str, int] = {}
    for f in files:
        if f.role == "creative":
            counts[f.channel] = counts.get(f.channel, 0) + 1
            for other in f.also_channels:
                counts[other] = counts.get(other, 0) + 1
    channels = [d.PackChannel(id=c["id"], name=c["name"], format=c.get("format"), files=counts.get(c["id"], 0)) for c in src.brief_channels]
    manifest = d.AssetPackManifest(
        schema_version=SCHEMA_VERSION, naming=NAMING, campaign_id=src.campaign.id, campaign_name=src.campaign.name, campaign_slug=c_slug,
        region_code=region_code, region_name=src.region.name, version=_version_view(src.node), approval=src.approval, channels=channels,
        files=files, excluded=excluded, notes=NOTES, mode=src.project.mode, generated_at=None,  # type: ignore[arg-type]
    )
    return _Built(manifest, payloads)


def _checksums(files: list[d.PackFile]) -> bytes:
    return "".join(f"{f.sha256}  {f.path}\n" for f in files).encode()


def build_zip(manifest: d.AssetPackManifest, payloads: dict[str, bytes], when: datetime) -> bytes:
    """The ZIP: sorted entries with the pack's own timestamp, so the same inputs and time give the same bytes."""
    entries = dict(payloads)
    entries["SHA256SUMS"] = _checksums(manifest.files)
    entries["manifest.json"] = (json.dumps(manifest.model_dump(mode="json"), ensure_ascii=False, indent=2) + "\n").encode()
    stamp = (max(when.year, 1980), when.month, when.day, when.hour, when.minute, when.second)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for path in sorted(entries):
            info = zipfile.ZipInfo(path, date_time=stamp)
            info.compress_type = zipfile.ZIP_STORED if path.rsplit(".", 1)[-1] in STORED_TYPES else zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, entries[path])
    return buffer.getvalue()



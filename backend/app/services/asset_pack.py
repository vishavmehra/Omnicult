"""Asset Pack (feature 40): a ZIP per region with the approved version's copy, its creative files, caption sidecars, the
Brand Kit files, and a manifest that carries provenance and checksums.

What goes in, by rule (nothing is guessed, and nothing is generated by a model):
- The version is one a signed-in member approved for the region (the newest standing `approve` decision, or the one asked for).
  A region with no standing approval has no pack.
- Copy: the version's elements as JSON and as text, plus an SRT built from its caption elements, timed by the bounds of the
  scenes they sit in (the timing is the original creative's, not a re-timed voice-over).
- Creative files: this campaign's registered creatives (Creative X-Ray) made for this region. Only a file whose rights the
  uploader confirmed and whose stored bytes still match the recorded SHA-256 goes in; every other file is listed under
  `excluded` with the reason.
- Brand Kit: the logo and product images linked in the Brand Kit (same rights rule), and the Brand Kit data as JSON.

Files are named `omc_<campaign>_<version>_<region>_<channel>`. A creative is named for a brief channel when the brief points
at it (`creative_ref`), else for the first channel whose format names its kind (video, image), else `all`.

The ZIP is built in a worker thread, stored like a Proof export (blob store; the row only for ASSET_STORAGE_BACKEND=database),
and served through a link whose random token is stored only as a hash, with an expiry. Every failure of that link is the same 404.
"""


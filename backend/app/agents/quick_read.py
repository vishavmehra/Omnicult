"""Audience Lab panel agents: Quick Read reactions and Audience Study interviews and analysis.

Reuses the existing building blocks (reading contexts from `agents.audience`, the interview schema and questions from
`agents.population`) and adds the region grounding: the model sees numbered region claims (C1, ...) and may cite them;
code maps every handle back to a stored claim and decides what is claim-supported. Everything the model writes is a
synthetic interpretation, never an observation, and never about a real person.
"""

from functools import lru_cache
from typing import Annotated, ClassVar

from pydantic import Field, create_model

from app.agents._common import Strict, untrusted
from app.agents.audience import reading_contexts
from app.agents.population import ANALYSIS_SYSTEM, CORE_QUESTIONS, FOLLOW_UPS, AnalysisOut, interviews_schema
from app.llm.gateway import LLMGateway, LLMResult
from app.schemas.population import Comprehension, ReactionCategory

QUICK_READ_PROMPT_VERSION = "quick-read-v1"
STUDY_INTERVIEW_PROMPT_VERSION = "audience-study-interviews-v1"
STUDY_ANALYSIS_PROMPT_VERSION = "audience-study-analysis-v1"
MAX_PER_CALL = 8

GROUNDING_RULES = (
    "Rules: the region claims are numbered (C1, C2, ...). When a statement about the region rests on a claim, cite its "
    "handle in `claims`. A statement that rests on no claim carries no citation and is your own interpretation: do not "
    "present it as fact. Never invent a claim, a statistic, a source or a handle. Each participant is described only by "
    "state, language, city tier and age band plus the style knobs shown: never infer or mention religion, caste, health, "
    "gender, sexuality, ethnicity, politics or income for a participant. Every participant is synthetic, generated by an "
    "AI model, and never a real person; do not claim otherwise. Avoid stereotypes: people in one state differ."
)


class PointOut(Strict):
    text: str = Field(min_length=1, max_length=240)
    claims: list[str] = Field(default=[], max_length=4, description="Region claim handles (C1, ...) the point rests on.")


class RatingsOut(Strict):
    clarity: int = Field(ge=1, le=5)
    cultural_relevance: int = Field(ge=1, le=5)
    cultural_risk: int = Field(ge=1, le=5, description="5 = most perceived cultural risk.")


class ParticipantOut(Strict):
    participant: str = Field(description="Participant handle, e.g. P1.")
    first_reaction: str = Field(min_length=1, max_length=300)
    sentiment: ReactionCategory
    message_restated: str = Field(min_length=1, max_length=240, description="The message in this participant's own words.")
    message_survival: Comprehension = Field(description="Whether the intended message survived for this participant.")
    positives: list[PointOut] = Field(default=[], max_length=3)
    negatives: list[PointOut] = Field(default=[], max_length=3)
    confusion: list[PointOut] = Field(default=[], max_length=3)
    regional_concerns: list[PointOut] = Field(default=[], max_length=3)
    ratings: RatingsOut
    follow_up_question: str = Field(min_length=1, max_length=200)
    relevant_passage: str | None = Field(default=None, max_length=300, description="Exact quote from the creative, or null.")


class _QuickReadBase(Strict):
    schema_version: ClassVar[str] = "quick-read-v1"


@lru_cache
def quick_read_schema(count: int) -> type[_QuickReadBase]:
    return create_model(
        "QuickReadOut", __base__=_QuickReadBase,
        participants=(Annotated[list[ParticipantOut], Field(min_length=1, max_length=count)], ...),
    )


QUICK_READ_SYSTEM = f"""You voice a small synthetic panel for Omnicult's Quick Read: a fast first reaction to one creative in
one region. For each participant, react to the creative as someone described by the given state, language, city tier and
age band would, in the given reading context. Give a first reaction, restate the message in the participant's own words and
say whether the intended message survived (understood, partial, misunderstood), then list positives, negatives, confusion
and regional concerns, three at most each, and rate clarity, cultural relevance and cultural risk from 1 to 5. Suggest one
follow-up question worth asking real people. Reactions may disagree; do not force consensus.
relevant_passage must quote the creative exactly, or be null.
{GROUNDING_RULES}"""


def participant_rows(people: list[dict], seed: int, offset: int) -> list[dict]:
    """Prompt rows with a handle and a seeded reading context each; the dimensions are the persona."""
    contexts = reading_contexts(seed, 0, len(people), offset)
    return [{"participant": f"P{n}", "ordinal": p["ordinal"], "persona": p["persona"], "state": p["state_name"],
             "language": p["language_name"], "city_tier": p["city_tier"], "age_band": p["age_band"], "traits": p["traits"],
             "reading_context": contexts[n - 1]} for n, p in enumerate(people, 1)]


async def quick_read(
    llm: LLMGateway, *, stage: str, rows: list[dict], creative: dict, intended_message: str | None, region: str,
    claims: list[dict], brand: str, seed: int,
) -> LLMResult:
    payload = {"participants": rows, "creative": creative, "intended_message": intended_message, "region": region, "claims": claims}
    user = "\n\n".join([
        f"Region: {region}. Voice each of the {len(rows)} participants.",
        untrusted("intended_message", intended_message or "not stated; judge from the creative itself."),
        brand,
        untrusted("creative", creative),
        untrusted("region_claims", claims),
        untrusted("participants", rows),
    ])
    return await llm.generate_structured(
        task="synthetic_generation", stage=stage, agent="audience", system=QUICK_READ_SYSTEM, user=user,
        schema=quick_read_schema(len(rows)), prompt_version=QUICK_READ_PROMPT_VERSION, temperature=0.8, seed=seed,
        max_tokens=700 * len(rows) + 300, fixture_context=payload,
    )


# --- Audience Study: the population interview schema, driven by the sampling dimensions ----------------------------------

STUDY_INTERVIEW_SYSTEM = f"""You voice synthetic participants in an Omnicult Audience Study. Each participant is an AI persona
described only by state, language, city tier, age band and a few style knobs; none is a real person. Answer every core
question in one or two short sentences in that participant's own voice about the creative shown, then add the requested
number of adaptive follow-up questions with their answers. Reactions may be positive, mixed, neutral, negative or
confused: never force agreement or diversity. Each participant answers independently. Themes and concerns are short labels.
{GROUNDING_RULES}"""


async def study_interviews(
    llm: LLMGateway, *, stage: str, rows: list[dict], depth: str, creative: dict, region: str, claims: list[dict], seed: int,
) -> LLMResult:
    follow_ups = FOLLOW_UPS[depth]
    payload = {"participants": rows, "depth": depth, "creative": creative, "region": region, "claims": claims}
    user = "\n\n".join([
        f"Regions: {region}. Interview each of the {len(rows)} participants. Core questions: "
        + "; ".join(f"{q}: {text}" for q, text in CORE_QUESTIONS) + f". Follow-ups per participant: {follow_ups}.",
        untrusted("creative", creative),
        untrusted("region_claims", claims),
        untrusted("participants", rows),
    ])
    return await llm.generate_structured(
        task="extraction", stage=stage, agent="audience", system=STUDY_INTERVIEW_SYSTEM, user=user,
        schema=interviews_schema(len(rows), follow_ups), prompt_version=STUDY_INTERVIEW_PROMPT_VERSION,
        temperature=0.8, seed=seed, max_tokens=500 * len(rows) + 300, fixture_context=payload,
    )


async def study_analysis(llm: LLMGateway, *, stage: str, tallies: dict, quotes: list[dict]) -> LLMResult[AnalysisOut]:
    payload = {"tallies": tallies, "quotes": quotes}
    user = "\n\n".join([untrusted("tallies", tallies), untrusted("sampled_quotes", quotes)])
    system = ANALYSIS_SYSTEM + " The participants were sampled by state, language, city tier and age band; slices are small and are not market segments."
    return await llm.generate_structured(
        task="research_synthesis", stage=stage, agent="analyst", system=system, user=user, schema=AnalysisOut,
        prompt_version=STUDY_ANALYSIS_PROMPT_VERSION, temperature=0.2, max_tokens=1500, fixture_context=payload,
    )

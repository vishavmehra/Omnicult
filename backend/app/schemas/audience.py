class SamplingPlan(ApiModel):
    """The only dimensions a panel is sampled by. Leave a dimension out to use its default (see the sampling options)."""

    states: Annotated[list[RegionCode], Field(min_length=1, max_length=5)] | None = None
    languages: Annotated[list[LanguageCode], Field(min_length=1, max_length=6)] | None = None
    city_tiers: Annotated[list[CityTier], Field(min_length=1, max_length=4)] | None = None
    age_bands: Annotated[list[AgeBand], Field(min_length=1, max_length=5)] | None = None
    weights: dict[str, dict[str, float]] | None = Field(
        default=None,
        description="Optional share per value, per dimension (for example {\"city_tiers\": {\"tier1\": 2, \"rural\": 1}}). "
        "Shares set panel composition by configuration; they are not market statistics.",
    )

    @model_validator(mode="before")
    @classmethod
    def _no_protected_traits(cls, data: Any) -> Any:
        if isinstance(data, dict):
            reject_protected(data)
        return data

    @field_validator("states")
    @classmethod
    def _known_states(cls, value: list[str] | None) -> list[str] | None:
        unknown = sorted(set(value or []) - KNOWN_REGIONS)
        if unknown:
            raise ValueError(f"Unknown state or union territory code(s): {', '.join(unknown)}.")
        if value and len(set(value)) != len(value):
            raise ValueError("List each state once.")
        return value

    @field_validator("languages")
    @classmethod
    def _known_languages(cls, value: list[str] | None) -> list[str] | None:
        unknown = sorted(set(value or []) - KNOWN_LANGUAGES)
        if unknown:
            raise ValueError(f"Unknown language code(s): {', '.join(unknown)}.")
        if value and len(set(value)) != len(value):
            raise ValueError("List each language once.")
        return value

    @field_validator("city_tiers", "age_bands")
    @classmethod
    def _unique(cls, value: list[str] | None) -> list[str] | None:
        if value and len(set(value)) != len(value):
            raise ValueError("List each value once.")
        return value

    @model_validator(mode="after")
    def _weights_match(self) -> "SamplingPlan":
        for name, shares in (self.weights or {}).items():
            if name not in DIMENSIONS:
                raise ValueError(f"weights.{name}: use one of {', '.join(DIMENSIONS)}.")
            listed = getattr(self, name)
            if listed is not None and set(shares) != set(listed):
                raise ValueError(f"weights.{name} must give a share for every listed value and no others.")
            if any(not math.isfinite(s) or s <= 0 for s in shares.values()):
                raise ValueError(f"weights.{name}: every share must be a positive number.")
        return self



class CreativeElementIn(ApiModel):
    """A creative element as the Creative Studio describes it. Held as JSON; there is no foreign key to a media table."""

    id: ElementId
    kind: ElementKind
    value: Any = Field(description="Text, or a description of the element. Text is what quotes are verified against.")
    language: str | None = Field(default=None, max_length=8)
    script: str | None = Field(default=None, max_length=8)
    bbox: Annotated[list[float], Field(min_length=4, max_length=4)] | None = Field(
        default=None, description="Normalised [x, y, width, height], each from 0 to 1."
    )
    scene_id: ElementId | None = None
    locked: bool = False

    @field_validator("bbox")
    @classmethod
    def _normalised(cls, v: list[float] | None) -> list[float] | None:
        if v is None:
            return v
        x, y, w, h = v
        if not all(math.isfinite(n) for n in v) or min(v) < 0 or max(v) > 1 or w <= 0 or h <= 0 or x + w > 1.0001 or y + h > 1.0001:
            raise ValueError("bbox must be normalised [x, y, width, height] inside the frame.")
        return v

    @field_validator("value")
    @classmethod
    def _bounded(cls, v: Any) -> Any:
        if len(str(v)) > 5000:
            raise ValueError("value is limited to 5000 characters.")
        return v


class CreativeSceneIn(ApiModel):
    id: ElementId
    start_ms: int | None = Field(default=None, ge=0)
    end_ms: int | None = Field(default=None, ge=0)
    summary: Annotated[str, StringConstraints(max_length=300)] | None = None

    @model_validator(mode="after")
    def _ordered(self) -> "CreativeSceneIn":
        if self.start_ms is not None and self.end_ms is not None and self.end_ms < self.start_ms:
            raise ValueError("end_ms must not be before start_ms.")
        return self


class RiskCheckCreate(ApiModel):
    """Check a creative's elements against the region's claims and the ad-code index. Without `elements`, the campaign
    version's headline, body and call to action are checked."""

    region_code: RegionCode
    elements: Annotated[list[CreativeElementIn], Field(min_length=1, max_length=60)] | None = None
    scenes: Annotated[list[CreativeSceneIn], Field(max_length=40)] = []
    content_version_id: UUID | None = None
    version_ref: VersionRef | None = None
    product_category: Term | None = Field(default=None, description="For example 'packaged snacks'; helps the check pick relevant clauses.")

    @model_validator(mode="after")
    def _unique_ids(self) -> "RiskCheckCreate":
        for label, items in (("elements", self.elements or []), ("scenes", self.scenes)):
            ids = [i.id for i in items]
            if len(set(ids)) != len(ids):
                raise ValueError(f"{label}: ids must be unique.")
        if self.elements and self.content_version_id is not None:
            raise ValueError("Give elements or content_version_id, not both.")
        return self


